static void fb_clear(void)
{
    for ( uint16_t i = 0; i < 1024; i++) framebuf[i] = 0 ;
}


static void fb_set_pixel(uint8_t x, uint8_t y, uint8_t on) {
    if (x >= 128 || y >= 64 ) return;
    uint16_t idx = x + (y / 8) * 128;
    uint8_t bit = 1 << (y & 7);
    if (on) framebuf[idx] |= bit;
    else    framebuf[idx] &= ~bit;
}

static void fb_draw_char( uint8_t col , uint8_t page , char c )
{/*
    uint8_t idx;
    if ( c >= '0' && c <= '9' ) idx = c - '0' ;
    else if (c == ':') idx = 10 ;
    else if( c > '9'   &&   c < ('z'+1) ) idx = c - 86 ;
    else return ;

    uint16_t offset = page *128 + col ;

    for (uint8_t i = 0 ; i < 5 ; i++ ) {
        if (offset + i < 1024) {
            framebuf[ offset + i ] = font_5x7[idx][i] ;
        }
    }*/

    if (c < ' ' || c > 'Z') c = '?';
    uint8_t idx = c - ' ' ;
    for (uint8_t colm = 0; colm < 5; colm++) {
        uint8_t bits = pgm_read_byte(&f5x7[idx][colm]);
        for (uint8_t row = 0; row < 7; row++) {
            if (bits & (1 << row)) {
                fb_set_pixel(col + colm, page + row, 1);
            }
        }
    }
}


static void fb_draw_string( uint8_t col, uint8_t page, const char *s )
{
    while (*s) {
        fb_draw_char( col, page, *s++  );
        col += 6 ;  /* set 6 for 5 pixels + 1 space */
    }
}



static void oled_flush(void)
{
    oled_cmd(0x21); oled_cmd(0); oled_cmd(127) ;  /* Column range */
    oled_cmd(0x22); oled_cmd(0); oled_cmd(7) ;    /* Page range */
    //oled_data( framebuf , 1024 ) ;
    

    twi_start() ;
    twi_write( OLEDI2CADDR << 1 );
    twi_write( CTRL_DATA );
    for( uint16_t i = 0 ; i < 1024 ; i++)
    {
        twi_write( framebuf[i] );

    }
    twi_stop() ;
}
