static void oled_cmd( uint8_t cmd )
{   
    twi_start() ;
    twi_write( OLEDI2CADDR << 1 );
    twi_write( CTRL_CMD );
    twi_write( cmd ) ;
    twi_stop() ;
};


static void oled_data( const uint8_t * buf , uint16_t len )
{
    twi_start() ;
    twi_write( OLEDI2CADDR << 1 ) ;
    twi_write( CTRL_DATA );
	for( uint16_t i = 0 ; i < len ; i++ ){
		twi_write(buf[i]) ;
	}
    twi_stop() ;
}



static void oled_init(void)
{
    _delay_ms(100);

    oled_cmd(0xAE);                      // display off
    oled_cmd(0xD5); oled_cmd(0x80);  // clock divide
    oled_cmd(0xA8); oled_cmd(0x3F);  // multiplex = 64
    oled_cmd(0xD3); oled_cmd(0x00);  // display offset = 0
    oled_cmd(0x40);               // start line = 0
    oled_cmd(0x8D); oled_cmd(0x14);  // charge pump on
    oled_cmd(0x20); oled_cmd(0x00);  // horizontal addressing mode
    oled_cmd(0xA1);               // segment remap
    oled_cmd(0xC8);               // COM scan dir flipped
    oled_cmd(0xDA); oled_cmd(0x12);  // COM pins config
    oled_cmd(0x81); oled_cmd(0xCF);  // contrast
    oled_cmd(0xD9); oled_cmd(0xF1);  // pre-charge
    oled_cmd(0xDB); oled_cmd(0x40);  // VCOMH deselect
    oled_cmd(0xA4);                      // resume from RAM
    oled_cmd(0xA6);                      // normal (not inverted)
    oled_cmd(0xAF);                      // display on
}


